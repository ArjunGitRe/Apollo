IF OBJECT_ID('[ext].[TSCECORESPRODUCTCATEGORYVIEW]') IS NOT NULL
BEGIN
    DROP VIEW [ext].[TSCECORESPRODUCTCATEGORYVIEW];
END;
GO

CREATE VIEW ext.TSCECORESPRODUCTCATEGORYVIEW AS
SELECT DISTINCT 
    EPC.PRODUCT, 
    EC.NAME AS CATEGORYNAME, 
    EC.LEVEL
FROM ax.ECORESPRODUCTCATEGORY EPC
LEFT JOIN ax.ECORESCATEGORY EC ON EPC.CATEGORY = EC.RECID 
AND EPC.CATEGORYHIERARCHY = EC.CATEGORYHIERARCHY

GO

GRANT SELECT ON OBJECT::[ext].[TSCECORESPRODUCTCATEGORYVIEW] TO [UsersRole];
GO

GRANT SELECT ON OBJECT::[ext].[TSCECORESPRODUCTCATEGORYVIEW] TO [DeployExtensibilityRole];
GO