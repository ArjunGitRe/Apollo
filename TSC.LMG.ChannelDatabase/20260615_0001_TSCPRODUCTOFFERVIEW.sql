IF OBJECT_ID('[ext].[TSCPRODUCTOFFERVIEW]') IS NOT NULL
BEGIN
    DROP VIEW [ext].[TSCPRODUCTOFFERVIEW];
END;
GO

CREATE VIEW [ext].[TSCPRODUCTOFFERVIEW] AS
SELECT 
    RGML.PRODUCT        AS PRODUCTID,
    RPDL.OFFERID        AS OFFERID,
    RCCT.COUPONCODE     AS COUPONCODE
FROM ax.RETAILGROUPMEMBERLINE RGML

INNER JOIN ax.RETAILPERIODICDISCOUNTLINE RPDL ON RPDL.RETAILGROUPMEMBERLINE = RGML.RECID
INNER JOIN ax.RETAILPERIODICDISCOUNT RPD ON RPD.OFFERID = RPDL.OFFERID
INNER JOIN ax.RETAILCOUPON RC ON RC.DISCOUNTOFFERID = RPD.OFFERID
INNER JOIN ax.RETAILCOUPONCODETABLE RCCT ON RCCT.COUPONNUMBER = RC.COUPONNUMBER;

GO

GRANT SELECT ON OBJECT::[ext].[TSCPRODUCTOFFERVIEW] TO [UsersRole];
GO

GRANT SELECT ON OBJECT::[ext].[TSCPRODUCTOFFERVIEW] TO [DeployExtensibilityRole];
GO


