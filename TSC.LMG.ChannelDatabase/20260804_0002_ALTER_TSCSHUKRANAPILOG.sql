-- 1. Add ID column (existing rows auto-populate with distinct GUIDs)
IF NOT EXISTS (
    SELECT * FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'ext'
      AND TABLE_NAME   = 'TSCSHUKRANAPILOG'
      AND COLUMN_NAME  = 'ID'
)
BEGIN
    ALTER TABLE [ext].[TSCSHUKRANAPILOG]
    ADD [ID] [nvarchar](50) NOT NULL
        CONSTRAINT [DF_TSCSHUKRANAPILOG_ID] DEFAULT (newid());
END
GO



-- 2. Rebuild PK to include ID (skips if already done)
IF NOT EXISTS (
    SELECT *
    FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA    = 'ext'
      AND TABLE_NAME      = 'TSCSHUKRANAPILOG'
      AND CONSTRAINT_NAME = 'PK_TSCSHUKRANAPILOG'
      AND COLUMN_NAME     = 'ID'
)
BEGIN
    IF EXISTS (
        SELECT * FROM sys.key_constraints
        WHERE [name] = 'PK_TSCSHUKRANAPILOG'
          AND [parent_object_id] = OBJECT_ID('[ext].[TSCSHUKRANAPILOG]')
    )
    BEGIN
        ALTER TABLE [ext].[TSCSHUKRANAPILOG]
        DROP CONSTRAINT [PK_TSCSHUKRANAPILOG];
    END



    ALTER TABLE [ext].[TSCSHUKRANAPILOG]
    ADD CONSTRAINT [PK_TSCSHUKRANAPILOG] PRIMARY KEY CLUSTERED
    (
		[CHANNEL] ASC,
        [STORE] ASC,
		[TERMINAL] ASC,
		[DATAAREAID] ASC,
		[ID] ASC
    ) WITH (PAD_INDEX = OFF, STATISTICS_NORECOMPUTE = OFF, IGNORE_DUP_KEY = OFF,
            ALLOW_ROW_LOCKS = ON, ALLOW_PAGE_LOCKS = ON,
            OPTIMIZE_FOR_SEQUENTIAL_KEY = OFF) ON [PRIMARY];
END