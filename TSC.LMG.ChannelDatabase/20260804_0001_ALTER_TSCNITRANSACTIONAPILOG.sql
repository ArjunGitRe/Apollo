    SELECT *
    FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE
    WHERE TABLE_SCHEMA    = 'ext'
      AND TABLE_NAME      = 'TSCNITRANSACTIONAPILOG'
      AND CONSTRAINT_NAME = 'PK_TSCNITRANSACTIONAPILOG'
      AND COLUMN_NAME     = 'ID'
)
BEGIN
    IF EXISTS (
        SELECT * FROM sys.key_constraints
        WHERE [name] = 'PK_TSCNITRANSACTIONAPILOG'
          AND [parent_object_id] = OBJECT_ID('[ext].[TSCNITRANSACTIONAPILOG]')
    )
    BEGIN
        ALTER TABLE [ext].[TSCNITRANSACTIONAPILOG]
        DROP CONSTRAINT [PK_TSCNITRANSACTIONAPILOG];
    END



    ALTER TABLE [ext].[TSCNITRANSACTIONAPILOG]
    ADD CONSTRAINT [PK_TSCNITRANSACTIONAPILOG] PRIMARY KEY CLUSTERED
    (
        [TRANSACTIONID] ASC,
        [STOREID] ASC,
        [TERMINALID] ASC,
        [DATAAREAID] ASC,
