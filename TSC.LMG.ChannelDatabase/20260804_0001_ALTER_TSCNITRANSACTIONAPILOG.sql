    SELECT * FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'ext'
      AND TABLE_NAME   = 'TSCNITRANSACTIONAPILOG'
      AND COLUMN_NAME  = 'ID'
)
BEGIN
    ALTER TABLE [ext].[TSCNITRANSACTIONAPILOG]
    ADD [ID] [nvarchar](50) NOT NULL
        CONSTRAINT [DF_TSCNITRANSACTIONAPILOG_ID] DEFAULT (newid());
END
GO



