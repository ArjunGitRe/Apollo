IF OBJECT_ID('[ext].[TSRETAILTRANSACTIONTABLEVIEW]') IS NOT NULL
BEGIN
    DROP VIEW [ext].[TSRETAILTRANSACTIONTABLEVIEW];
END;
GO

CREATE VIEW [ext].[TSRETAILTRANSACTIONTABLEVIEW] AS 
SELECT
    RTT.STORE,
    RTT.TERMINAL,
    RTT.TRANSACTIONID,
    RTT.RECEIPTID,
	RTT.BEGINDATETIME,
    DATEADD(SECOND, RTT.TRANSTIME, CAST(RTT.TRANSDATE AS DATETIME)) AS TRANSDATETIME

FROM [ax].[RETAILTRANSACTIONTABLE] RTT
JOIN [ext].[TSCRETAILTRANSACTIONTABLEEXT] TRTTE
    ON  RTT.CHANNEL       = TRTTE.CHANNEL
    AND RTT.STORE         = TRTTE.STORE
    AND RTT.TERMINAL      = TRTTE.TERMINAL
    AND RTT.TRANSACTIONID = TRTTE.TRANSACTIONID
    AND RTT.DATAAREAID    = TRTTE.DATAAREAID
GO

